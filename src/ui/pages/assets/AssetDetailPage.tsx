/**
 * Asset detail — port of `templates/assets/detail.html` and `view_asset()`.
 *
 * Three source display bugs are fixed here and recorded in docs/DEVIATIONS.md:
 *   * Cost/Charges is a percentage but the template ran it through `currency`;
 *   * Interest Rate went through `percentage`, which multiplies by 100, so a
 *     stored 1.25 printed as "125.00%";
 *   * the snapshot "% Change" column applied ×100 twice ("+500.0%" for +5 %).
 */

import { useState } from "react";
import { Link, useNavigate, useParams } from "react-router-dom";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { deleteAsset, getAssetRow } from "../../../db/repositories/assets";
import { listSnapshotsForAsset } from "../../../db/repositories/snapshots";
import {
  autoGeneratedName,
  buildHistory,
  displayName,
  formattedCurrency,
} from "../../../domain/assets";
import {
  formatDate,
  formatMinorAsCurrency,
  formatPercentage,
  formatPercentValue,
  relativeDate,
} from "../../../domain/format";
import { AssetDeleteModal } from "../../components/AssetDeleteModal";
import { PageHeader } from "../../components/FormCard";
import { TagBadge } from "../../components/SearchFilter";
import { AssetEvolutionChart } from "../../charts/AssetEvolutionChart";
import { useToast } from "../../layout/Toasts";

export function AssetDetailPage() {
  const { assetId } = useParams();
  const id = Number(assetId);
  const navigate = useNavigate();
  const toast = useToast();
  const queryClient = useQueryClient();
  const [confirmDelete, setConfirmDelete] = useState(false);

  const assetQuery = useQuery({ queryKey: ["asset-row", id], queryFn: () => getAssetRow(id) });
  const snapshotsQuery = useQuery({ queryKey: ["snapshots", id], queryFn: () => listSnapshotsForAsset(id) });

  const remove = useMutation({
    mutationFn: () => deleteAsset(id),
    onSuccess: () => {
      for (const key of ["assets", "snapshot-points", "snapshots", "asset-row"]) {
        void queryClient.invalidateQueries({ queryKey: [key] });
      }
      toast.success(`Asset "${name}" deleted successfully!`);
      navigate("/assets");
    },
    onError: (error: unknown) => {
      setConfirmDelete(false);
      toast.error(`Error deleting asset: ${error instanceof Error ? error.message : String(error)}`);
    },
  });

  const asset = assetQuery.data;
  const name = asset ? displayName(asset) : "";

  if (assetQuery.isLoading || snapshotsQuery.isLoading) return <p className="text-muted">Loading…</p>;

  if (!asset) {
    return (
      <div className="alert alert-warning">
        <i className="bi bi-exclamation-triangle me-2" aria-hidden="true" />
        The requested asset was not found. <Link to="/assets">Back to Assets</Link>
      </div>
    );
  }

  const history = buildHistory(snapshotsQuery.data ?? []);
  const latest = history[0] ?? null;
  const oldest = history.length >= 2 ? history[history.length - 1] : null;

  return (
    <>
      <PageHeader
        title={name}
        subtitle="Asset Details and History"
        showDate={false}
        actions={
          <>
            <Link to={`/snapshots/new?asset_id=${asset.id}`} className="btn btn-primary btn-sm">
              <i className="bi bi-camera" aria-hidden="true" />
              Add Snapshot
            </Link>
            <Link to={`/assets/${asset.id}/edit`} className="btn btn-secondary btn-sm">
              <i className="bi bi-pencil" aria-hidden="true" />
              Edit
            </Link>
            <button type="button" className="btn btn-outline-danger btn-sm" onClick={() => setConfirmDelete(true)}>
              <i className="bi bi-trash" aria-hidden="true" />
              Delete
            </button>
          </>
        }
      />

      <div className="row">
        <div className="col-lg-4 mb-4">
          <div className="card asset-detail-card">
            <div className="card-header">
              <h5 className="card-title mb-0">
                <i className="bi bi-info-circle me-2" aria-hidden="true" />
                Asset Information
              </h5>
            </div>
            <div className="card-body">
              {asset.name ? (
                <div className="row mb-3">
                  <div className="col-12">
                    <span className="asset-info-label">Custom Name:</span>
                    <br />
                    <span className="asset-info-value h6">{asset.name}</span>
                  </div>
                </div>
              ) : null}

              {asset.description ? (
                <div className="row mb-3">
                  <div className="col-12">
                    <span className="asset-info-label">Description:</span>
                    <br />
                    <span className="asset-info-value">{asset.description}</span>
                  </div>
                </div>
              ) : null}

              <div className="row mb-3">
                <div className="col-12">
                  <span className="asset-info-label">Notes:</span>
                  <br />
                  {asset.notes ? (
                    <span className="asset-info-value" style={{ whiteSpace: "pre-wrap" }}>{asset.notes}</span>
                  ) : (
                    <span className="text-muted fst-italic">
                      No notes yet. <Link to={`/assets/${asset.id}/edit`}>Add notes</Link>
                    </span>
                  )}
                </div>
              </div>

              {asset.name ? (
                <div className="row mb-3">
                  <div className="col-12">
                    <span className="asset-info-label">Auto-generated Name:</span>
                    <br />
                    <span className="asset-info-value text-muted">{autoGeneratedName(asset)}</span>
                  </div>
                </div>
              ) : null}

              <InfoRow label="Institution:">
                <span className="asset-info-value">{asset.institution_name}</span>
              </InfoRow>
              <InfoRow label="Product:">
                <span className="asset-info-value">{asset.product_name}</span>
              </InfoRow>
              <InfoRow label="Category:">
                <span className="badge bg-primary">{asset.category_name}</span>
              </InfoRow>
              <InfoRow label="Currency:">
                <span className="currency-display">{formattedCurrency(asset.currency)}</span>
              </InfoRow>

              {asset.code_nin ? (
                <InfoRow label="Code/NIN:">
                  <span className="asset-info-value">{asset.code_nin}</span>
                </InfoRow>
              ) : null}
              {asset.cost_charges && Number(asset.cost_charges) !== 0 ? (
                <InfoRow label="Cost/Charges:">
                  <span className="asset-info-value">{formatPercentValue(asset.cost_charges)}</span>
                </InfoRow>
              ) : null}
              {asset.interest_rate && Number(asset.interest_rate) !== 0 ? (
                <InfoRow label="Interest Rate:">
                  <span className="asset-info-value">{formatPercentValue(asset.interest_rate)}</span>
                </InfoRow>
              ) : null}

              {asset.tags.length > 0 ? (
                <div className="row mb-3">
                  <div className="col-12">
                    <span className="asset-info-label d-block mb-2">Tags:</span>
                    {asset.tags.map((tag) => (
                      <TagBadge key={tag.id} name={tag.name} color={tag.color} />
                    ))}
                  </div>
                </div>
              ) : null}

              <div className="row">
                <div className="col-6">
                  <span className="asset-info-label">Created:</span>
                </div>
                <div className="col-6">
                  <span className="asset-info-value">{formatDate(asset.created_at.slice(0, 10))}</span>
                </div>
              </div>
            </div>
          </div>
        </div>

        <div className="col-lg-4 mb-4">
          <div className="card">
            <div className="card-header">
              <h5 className="card-title mb-0">
                <i className="bi bi-graph-up me-2" aria-hidden="true" />
                Current Value
              </h5>
            </div>
            <div className="card-body text-center">
              {latest ? (
                <>
                  <div className="amount-display mb-2">
                    {formatMinorAsCurrency(latest.amount_minor, asset.currency)}
                  </div>
                  <p className="text-muted mb-0">Last updated: {relativeDate(latest.date)}</p>
                  <p className="text-muted small">{formatDate(latest.date)}</p>
                </>
              ) : (
                <div className="text-muted">
                  <i className="bi bi-graph-up icon-3x mb-3" aria-hidden="true" />
                  <h5>No snapshots recorded</h5>
                  <p>Add a snapshot to track this asset's value over time.</p>
                  <Link to={`/snapshots/new?asset_id=${asset.id}`} className="btn btn-primary">
                    <i className="bi bi-plus-lg me-2" aria-hidden="true" />
                    Add Snapshot
                  </Link>
                </div>
              )}
            </div>
          </div>
        </div>

        <div className="col-lg-4 mb-4">
          <div className="card">
            <div className="card-header">
              <h5 className="card-title mb-0">
                <i className="bi bi-bar-chart me-2" aria-hidden="true" />
                Statistics
              </h5>
            </div>
            <div className="card-body">
              <div className="row text-center">
                <div className="col-12 mb-3">
                  <div className="h4 mb-1">{history.length}</div>
                  <small className="text-muted">Total Snapshots</small>
                </div>
              </div>

              {latest && oldest ? (
                <>
                  <hr />
                  <div className="row text-center">
                    <div className="col-6">
                      <div className="h6 money mb-1">{formatMinorAsCurrency(latest.amount_minor, asset.currency)}</div>
                      <small className="text-muted">Latest</small>
                    </div>
                    <div className="col-6">
                      <div className="h6 money mb-1 text-muted">{formatMinorAsCurrency(oldest.amount_minor, asset.currency)}</div>
                      <small className="text-muted">Oldest</small>
                    </div>
                  </div>
                </>
              ) : null}
            </div>
          </div>
        </div>
      </div>

      <div className="row mb-4">
        <div className="col-12">
          <div className="card">
            <div className="card-header">
              <h5 className="card-title mb-0">
                <i className="bi bi-graph-up me-2" aria-hidden="true" />
                Value Evolution
              </h5>
            </div>
            <div className="card-body">
              <AssetEvolutionChart
                currency={asset.currency}
                points={history.map((row) => ({ date: row.date, amountMinor: row.amount_minor }))}
              />
            </div>
          </div>
        </div>
      </div>

      <div className="row">
        <div className="col-12">
          <div className="card">
            <div className="card-header d-flex justify-content-between align-items-center">
              <h5 className="card-title mb-0">
                <i className="bi bi-clock-history me-2" aria-hidden="true" />
                Snapshot History
              </h5>
              <Link to={`/snapshots/new?asset_id=${asset.id}`} className="btn btn-sm btn-primary">
                <i className="bi bi-plus-lg me-2" aria-hidden="true" />
                Add Snapshot
              </Link>
            </div>
            <div className="card-body">
              {history.length > 0 ? (
                <div className="table-responsive">
                  <table className="table table-hover">
                    <thead className="table-light">
                      <tr>
                        <th>Date</th>
                        <th className="text-end">Amount</th>
                        <th className="text-end">Change</th>
                        <th className="text-end">% Change</th>
                        <th className="text-end">Actions</th>
                      </tr>
                    </thead>
                    <tbody>
                      {history.map((row) => (
                        <tr className="snapshot-row" key={row.id}>
                          <td>
                            <strong>{formatDate(row.date, "%B %d, %Y")}</strong>
                            <br />
                            <small className="text-muted">{relativeDate(row.date)}</small>
                          </td>
                          <td className="text-end">
                            <strong>{formatMinorAsCurrency(row.amount_minor, asset.currency)}</strong>
                          </td>
                          <td className="text-end">
                            {row.changeMinor === null || row.changeMinor === 0 ? (
                              <span className="text-muted">-</span>
                            ) : row.changeMinor > 0 ? (
                              <span className="text-success">+{formatMinorAsCurrency(row.changeMinor, asset.currency)}</span>
                            ) : (
                              <span className="text-danger">{formatMinorAsCurrency(row.changeMinor, asset.currency)}</span>
                            )}
                          </td>
                          <td className="text-end">
                            {row.changeFraction === null || row.changeFraction.isZero() ? (
                              <span className="text-muted">-</span>
                            ) : row.changeFraction.greaterThan(0) ? (
                              <span className="text-success">+{formatPercentage(row.changeFraction, 1)}</span>
                            ) : (
                              <span className="text-danger">{formatPercentage(row.changeFraction, 1)}</span>
                            )}
                          </td>
                          <td className="text-end">
                            <div className="btn-group btn-group-sm" role="group">
                              <Link to={`/snapshots/${row.id}/edit`} className="btn btn-outline-secondary">
                                <i className="bi bi-pencil-square me-1" aria-hidden="true" />
                                Edit
                              </Link>
                            </div>
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              ) : (
                <div className="text-center py-4">
                  <i className="bi bi-graph-up icon-3x text-muted mb-3" aria-hidden="true" />
                  <h5>No snapshots recorded</h5>
                  <p className="text-muted">Start tracking this asset's value by adding your first snapshot.</p>
                  <Link to={`/snapshots/new?asset_id=${asset.id}`} className="btn btn-primary">
                    <i className="bi bi-plus-lg me-2" aria-hidden="true" />
                    Add First Snapshot
                  </Link>
                </div>
              )}
            </div>
          </div>
        </div>
      </div>

      <AssetDeleteModal
        name={confirmDelete ? name : null}
        snapshotCount={history.length}
        onCancel={() => setConfirmDelete(false)}
        onConfirm={async () => {
          await remove.mutateAsync();
        }}
      />
    </>
  );
}

function InfoRow({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="row mb-3">
      <div className="col-6">
        <span className="asset-info-label">{label}</span>
      </div>
      <div className="col-6">{children}</div>
    </div>
  );
}
