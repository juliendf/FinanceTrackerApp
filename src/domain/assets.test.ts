function asset(overrides: Partial<AssetRow> & { id: number }): AssetRow {
  return {
    institution_id: 1,
    category_id: 1,
    currency: "EUR",
    product_name: "Savings",
    name: null,
    description: null,
    notes: null,
    code_nin: null,
    cost_charges: null,
    interest_rate: null,
    created_at: "2025-01-01T00:00:00Z",
    updated_at: "2025-01-01T00:00:00Z",
    institution_name: "UBS",
    category_name: "Cash",
    category_color: null,
    latest_amount_minor: 100_00,
    latest_date: "2026-01-01",
    tags: [],
    ...overrides,
  };
}

