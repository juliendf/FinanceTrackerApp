describe("buildHistory — detail.html arithmetic", () => {
  const snaps = [
    { id: 1, date: "2025-01-01", amount_minor: 100_00 },
    { id: 2, date: "2025-02-01", amount_minor: 105_00 },
    { id: 3, date: "2025-03-01", amount_minor: 105_00 },
    { id: 4, date: "2025-04-01", amount_minor: 84_00 },
  ];

  it("lists newest first", () => {
    expect(buildHistory(snaps).map((r) => r.id)).toEqual([4, 3, 2, 1]);
  });

  it("compares each row with the next-older one, leaving the oldest blank", () => {
    const history = buildHistory(snaps);
    expect(history.map((r) => r.changeMinor)).toEqual([-21_00, 0, 5_00, null]);
    expect(history[3].changeFraction).toBeNull();
  });

  it("returns a *fraction*, so the percentage filter's x100 yields the right figure", () => {
    const history = buildHistory(snaps);
    // +5 -> 105 from 100 is +5 %, i.e. 0.05, not 5.
    expect(history[2].changeFraction?.toString()).toBe("0.05");
    expect(history[0].changeFraction?.toString()).toBe("-0.2");
  });

  it("gives no percentage when the previous value is zero", () => {
    const history = buildHistory([
      { id: 1, date: "2025-01-01", amount_minor: 0 },
      { id: 2, date: "2025-02-01", amount_minor: 50_00 },
    ]);
    expect(history[0].changeMinor).toBe(50_00);
    expect(history[0].changeFraction).toBeNull();
  });

  it("handles no snapshots and a single one", () => {
    expect(buildHistory([])).toEqual([]);
    expect(buildHistory([snaps[0]])[0]).toMatchObject({ changeMinor: null, changeFraction: null });
  });
});
