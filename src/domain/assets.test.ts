describe("summariseAssetList", () => {
  const rates = new RateTable([
    { from_currency: "EUR", to_currency: "CHF", rate: "0.9319" },
    { from_currency: "EUR", to_currency: "USD", rate: "1.1367" },
  ]);

  it("totals the latest value per currency and counts assets without a snapshot", () => {
    const summary = summariseAssetList(ROWS, rates, "EUR");
    expect(summary.totalAssets).toBe(4);
    expect(summary.noSnapshotCount).toBe(1);
    const eur = summary.byCurrency.find((b) => b.currency === "EUR");
    expect(eur).toMatchObject({ totalMinor: 2000_00, assets: 1, snapshots: 1 });
  });

  it("converts to the base currency with direct and inverse rates", () => {
    // 1000 CHF -> EUR uses the inverse of EUR->CHF; 500 USD -> EUR inverse of EUR->USD.
    const summary = summariseAssetList(ROWS, rates, "EUR");
    const expected = new Decimal(1000).dividedBy("0.9319").plus(2000).plus(new Decimal(500).dividedBy("1.1367"));
    expect(summary.combined).toEqual({
      totalMinor: expected.times(100).toDecimalPlaces(0, Decimal.ROUND_HALF_EVEN).toNumber(),
      currency: "EUR",
    });
  });

  it("hides the combined total when a rate is missing", () => {
    const partial = new RateTable([{ from_currency: "EUR", to_currency: "CHF", rate: "0.9319" }]);
    expect(summariseAssetList(ROWS, partial, "EUR").combined).toBeNull();
  });

  it("uses no currency hop: a path only through a third currency is not enough", () => {
    // CHF->USD exists only via EUR; the summary, like convert_amount, refuses it.
    const viaEur = new RateTable([
      { from_currency: "EUR", to_currency: "CHF", rate: "0.9319" },
      { from_currency: "EUR", to_currency: "USD", rate: "1.1367" },
    ]);
    expect(summariseAssetList([ROWS[0]], viaEur, "USD").combined).toBeNull();
  });

  it("has no combined total for an empty list", () => {
    expect(summariseAssetList([], rates, "EUR")).toEqual({
      totalAssets: 0, byCurrency: [], noSnapshotCount: 0, combined: null,
    });
  });
});

describe("assetCreateSchema — AssetForm", () => {
  const valid = {
    institution_id: "1", category_id: "2", product_name: "Savings", currency: "EUR" as const,
    name: "", description: "", notes: "", code_nin: "", cost_charges: "", interest_rate: "", tags: [] as string[],
    create_initial_snapshot: false, initial_amount: "", initial_date: "2026-01-01",
  };
  const issues = (value: unknown) => {
    const result = assetCreateSchema.safeParse(value);
    return result.success ? [] : result.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`);
  };

  it("accepts a minimal asset", () => {
    expect(assetCreateSchema.safeParse(valid).success).toBe(true);
  });

  it("requires an institution and a category", () => {
    expect(issues({ ...valid, institution_id: "" })).toContain("institution_id: Please select an institution.");
    expect(issues({ ...valid, category_id: "" })).toContain("category_id: Please select a category.");
  });

  it("requires a product name of 1..100 characters", () => {
    expect(issues({ ...valid, product_name: "  " })).toContain("product_name: Please enter a product name");
    expect(issues({ ...valid, product_name: "a".repeat(101) })).toContain(
      "product_name: Product name must be between 1 and 100 characters",
    );
  });

  it("rejects currencies other than EUR, USD, CHF", () => {
    expect(assetCreateSchema.safeParse({ ...valid, currency: "GBP" }).success).toBe(false);
  });

  it("caps the free-text fields", () => {
    expect(assetCreateSchema.safeParse({ ...valid, name: "a".repeat(101) }).success).toBe(false);
    expect(assetCreateSchema.safeParse({ ...valid, description: "a".repeat(1001) }).success).toBe(false);
    expect(assetCreateSchema.safeParse({ ...valid, notes: "a".repeat(5001) }).success).toBe(false);
    expect(assetCreateSchema.safeParse({ ...valid, code_nin: "a".repeat(51) }).success).toBe(false);
    expect(assetCreateSchema.safeParse({ ...valid, notes: "a".repeat(5000) }).success).toBe(true);
  });

  it("limits cost/charges and interest rate to 0..100", () => {
    expect(assetCreateSchema.safeParse({ ...valid, interest_rate: "100" }).success).toBe(true);
    expect(assetCreateSchema.safeParse({ ...valid, interest_rate: "100.01" }).success).toBe(false);
    expect(assetCreateSchema.safeParse({ ...valid, cost_charges: "-1" }).success).toBe(false);
    expect(assetCreateSchema.safeParse({ ...valid, cost_charges: "abc" }).success).toBe(false);
  });

  it("requires an amount when the initial snapshot box is ticked", () => {
    expect(issues({ ...valid, create_initial_snapshot: true, initial_amount: "" })).toContain(
      'initial_amount: Please enter an initial amount or uncheck "Create Initial Snapshot".',
    );
    expect(assetCreateSchema.safeParse({ ...valid, create_initial_snapshot: true, initial_amount: "1500.50" }).success).toBe(true);
  });

  it("requires a positive amount, with 0.01 as the floor", () => {
    for (const amount of ["0", "-5", "0.001", "abc"]) {
      expect(issues({ ...valid, create_initial_snapshot: true, initial_amount: amount })).toContain(
        "initial_amount: Amount must be greater than 0",
      );
    }
    expect(assetCreateSchema.safeParse({ ...valid, create_initial_snapshot: true, initial_amount: "0.01" }).success).toBe(true);
  });

  it("ignores snapshot fields on the edit schema", () => {
    expect(assetEditSchema.safeParse({ ...valid, create_initial_snapshot: true, initial_amount: "" }).success).toBe(true);
  });
});

