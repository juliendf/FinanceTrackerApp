describe("names — Asset.display_name", () => {
  const parts = { name: null, institution_name: "UBS", product_name: "Savings", category_name: "Cash" };

  it("generates 'institution - product (category)'", () => {
    expect(autoGeneratedName(parts)).toBe("UBS - Savings (Cash)");
    expect(displayName(parts)).toBe("UBS - Savings (Cash)");
  });

  it("prefers the custom name", () => {
    expect(displayName({ ...parts, name: "My rainy day fund" })).toBe("My rainy day fund");
    expect(autoGeneratedName({ ...parts, name: "My rainy day fund" })).toBe("UBS - Savings (Cash)");
  });

  it("falls back to Unknown for missing parts", () => {
    expect(autoGeneratedName({ name: null, institution_name: "", product_name: "", category_name: "" })).toBe(
      "Unknown - Unknown (Unknown)",
    );
  });

  it("formats the currency symbol like Asset.formatted_currency", () => {
    expect(formattedCurrency("EUR")).toBe("€");
    expect(formattedCurrency("USD")).toBe("$");
    expect(formattedCurrency("CHF")).toBe("CHF");
    expect(formattedCurrency("GBP")).toBe("GBP");
  });
});

describe("URL filters — list_assets request.args", () => {
  it("defaults like the route", () => {
    expect(parseAssetFilters(new URLSearchParams())).toEqual(EMPTY_FILTERS);
  });

  it("reads and trims every parameter", () => {
    const filters = parseAssetFilters(
      new URLSearchParams("search=%20ubs%20&currency=CHF&category=Cash&institution=UBS&tag=Liquid&page=3&per_page=50"),
    );
    expect(filters).toEqual({
      search: "ubs", currency: "CHF", category: "Cash", institution: "UBS", tag: "Liquid", page: 3, perPage: 50,
    });
  });

  it("falls back on non-numeric page and per_page, as type=int does", () => {
    const filters = parseAssetFilters(new URLSearchParams("page=abc&per_page=x"));
    expect(filters.page).toBe(1);
    expect(filters.perPage).toBe(20);
  });

  it("clamps per_page into 1..100, as paginate_query does", () => {
    expect(parseAssetFilters(new URLSearchParams("per_page=500")).perPage).toBe(100);
    expect(parseAssetFilters(new URLSearchParams("per_page=0")).perPage).toBe(1);
    expect(parseAssetFilters(new URLSearchParams("per_page=-5")).perPage).toBe(1);
  });

  it("serialises without defaults", () => {
    expect(assetFiltersToParams(EMPTY_FILTERS).toString()).toBe("");
    expect(assetFiltersToParams({ ...EMPTY_FILTERS, search: "ubs", page: 2, perPage: 50 }).toString()).toBe(
      "search=ubs&page=2&per_page=50",
    );
  });

  it("round-trips", () => {
    const filters = { ...EMPTY_FILTERS, currency: "EUR", tag: "Liquid", page: 4, perPage: 10 };
    expect(parseAssetFilters(assetFiltersToParams(filters))).toEqual(filters);
  });

  it("falls back to the Items Per Page setting when the URL has no per_page", () => {
    expect(parseAssetFilters(new URLSearchParams(), { perPage: 50 }).perPage).toBe(50);
  });

  it("lets an explicit per_page win over the setting", () => {
    expect(parseAssetFilters(new URLSearchParams("per_page=10"), { perPage: 50 }).perPage).toBe(10);
  });

  it("survives a corrupt setting rather than yielding NaN", () => {
    // The setting is TEXT coerced with Number(): a bad row gives NaN, which
    // would otherwise reach paginate and blank the list.
    expect(parseAssetFilters(new URLSearchParams(), { perPage: Number.NaN }).perPage).toBe(20);
    expect(parseAssetFilters(new URLSearchParams(), { perPage: 0 }).perPage).toBe(1);
    expect(parseAssetFilters(new URLSearchParams(), { perPage: 5000 }).perPage).toBe(100);
  });

  it("does not pin the setting into the URL when serialising", () => {
    const defaults = { perPage: 50 };
    // An unchanged view writes nothing, so changing the setting later still applies.
    expect(assetFiltersToParams({ ...EMPTY_FILTERS, perPage: 50 }, defaults).toString()).toBe("");
    expect(assetFiltersToParams({ ...EMPTY_FILTERS, perPage: 10 }, defaults).toString()).toBe("per_page=10");
  });
});

describe("filterAssets — the list_assets WHERE clause", () => {
  const none = { search: "", currency: "", category: "", institution: "", tag: "" };

  it("sorts by institution then product, case-insensitively", () => {
    // "Boursorama" and "boursorama" are one institution to the collation; Courant < PEA.
    expect(filterAssets(ROWS, none).map((r) => r.id)).toEqual([3, 2, 4, 1]);
  });

  it("searches institution, product, category and code/NIN, case-insensitively", () => {
    const ids = (search: string) => filterAssets(ROWS, { ...none, search }).map((r) => r.id).sort();
    expect(ids("ubs")).toEqual([1]);
    expect(ids("PEA")).toEqual([2]);
    expect(ids("crypto")).toEqual([4]);
    expect(ids("fr7612")).toEqual([2]);
    expect(ids("cash")).toEqual([1, 3]);
    expect(ids("nothing")).toEqual([]);
  });

  it("does not search notes or descriptions", () => {
    const rows = [asset({ id: 9, notes: "findme", description: "findme" })];
    expect(filterAssets(rows, { ...none, search: "findme" })).toEqual([]);
  });

  it("filters by exact currency, category, institution and tag name", () => {
    expect(filterAssets(ROWS, { ...none, currency: "EUR" }).map((r) => r.id).sort()).toEqual([2, 3]);
    expect(filterAssets(ROWS, { ...none, category: "Cash" }).map((r) => r.id).sort()).toEqual([1, 3]);
    expect(filterAssets(ROWS, { ...none, institution: "UBS" }).map((r) => r.id)).toEqual([1]);
    expect(filterAssets(ROWS, { ...none, tag: "Illiquide" }).map((r) => r.id)).toEqual([2]);
  });

  it("treats institution and category as exact, not substring", () => {
    expect(filterAssets(ROWS, { ...none, institution: "UB" })).toEqual([]);
    expect(filterAssets(ROWS, { ...none, category: "Cas" })).toEqual([]);
  });

  it("combines filters with AND", () => {
    expect(filterAssets(ROWS, { ...none, currency: "EUR", category: "Cash" }).map((r) => r.id)).toEqual([3]);
    expect(filterAssets(ROWS, { ...none, currency: "CHF", tag: "Illiquide" })).toEqual([]);
  });

  it("does not mutate its input", () => {
    const copy = [...ROWS];
    filterAssets(ROWS, none);
    expect(ROWS).toEqual(copy);
    sortAssets(ROWS);
    expect(ROWS).toEqual(copy);
  });
});

