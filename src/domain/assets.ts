/**
 * Asset screens' pure logic: display names, filtering, summary tiles, the form
 * schema, and the snapshot history deltas.
 *
 * Ports of `Asset.display_name` (`models/core.py`), the query in `list_assets`
 * (`routes/assets.py`), `AssetForm` (`forms/asset_forms.py`) and the arithmetic
 * in `templates/assets/detail.html`. The source filters in SQL; here the whole
 * asset set is a few hundred rows at most, so it is filtered in memory, which
 * keeps this module pure and testable.
 */

import Decimal from "decimal.js";
import { z } from "zod";
import { convertStrict, NoRateError, type RateTable } from "./currency";
import { fromMinorUnits, toMinorUnits } from "./money";

/** What the list screen needs per asset, tags included. */
export interface AssetRow {
  id: number;
  institution_id: number;
  category_id: number;
  currency: string;
  product_name: string;
  name: string | null;
  description: string | null;
  notes: string | null;
  code_nin: string | null;
  cost_charges: string | null;
  interest_rate: string | null;
  created_at: string;
  updated_at: string;
  institution_name: string;
  category_name: string;
  category_color: string | null;
  latest_amount_minor: number | null;
  latest_date: string | null;
  tags: Array<{ id: number; name: string; color: string | null }>;
}

// --- names ------------------------------------------------------------------

interface NameParts {
  name: string | null;
  institution_name: string;
  product_name: string;
  category_name: string;
}

/** `Asset.auto_generated_name`. */
export function autoGeneratedName(row: NameParts): string {
  return `${row.institution_name || "Unknown"} - ${row.product_name || "Unknown"} (${row.category_name || "Unknown"})`;
}

/** `Asset.display_name`: the custom name, else the generated one. */
export function displayName(row: NameParts): string {
  return row.name ? row.name : autoGeneratedName(row);
}

/** `Asset.formatted_currency`. */
export function formattedCurrency(currency: string): string {
  return ({ EUR: "€", USD: "$", CHF: "CHF" } as Record<string, string>)[currency] ?? currency;
}

// --- filters ----------------------------------------------------------------

export const DEFAULT_PER_PAGE = 20;
export const MAX_PER_PAGE = 100;

export interface AssetFilters {
  search: string;
  currency: string;
  category: string;
  institution: string;
  tag: string;
  page: number;
  perPage: number;
}

export const EMPTY_FILTERS: AssetFilters = {
  search: "",
  currency: "",
  category: "",
  institution: "",
  tag: "",
  page: 1,
  perPage: DEFAULT_PER_PAGE,
};

/** Flask's `request.args.get(..., type=int)`: anything unparseable falls back. */
function intParam(value: string | null, fallback: number): number {
  if (value === null || !/^[+-]?\d+$/.test(value.trim())) return fallback;
  return Number.parseInt(value, 10);
}

/** Read the URL query the way `list_assets` reads `request.args`. */
export function parseAssetFilters(params: URLSearchParams): AssetFilters {
  const perPage = intParam(params.get("per_page"), DEFAULT_PER_PAGE);
  return {
    search: (params.get("search") ?? "").trim(),
    currency: (params.get("currency") ?? "").trim(),
    category: (params.get("category") ?? "").trim(),
    institution: (params.get("institution") ?? "").trim(),
    tag: (params.get("tag") ?? "").trim(),
    page: intParam(params.get("page"), 1),
    // paginate_query: min(per_page, 100), then max(per_page, 1)
    perPage: Math.max(Math.min(perPage, MAX_PER_PAGE), 1),
  };
}

/** Serialise filters back to a query, leaving defaults out so URLs stay short. */
export function assetFiltersToParams(filters: Partial<AssetFilters>): URLSearchParams {
  const params = new URLSearchParams();
  for (const key of ["search", "currency", "category", "institution", "tag"] as const) {
    const value = filters[key];
    if (value) params.set(key, value);
  }
  if (filters.page && filters.page > 1) params.set("page", String(filters.page));
  if (filters.perPage && filters.perPage !== DEFAULT_PER_PAGE) {
    params.set("per_page", String(filters.perPage));
  }
  return params;
}

/** Collation-insensitive text compare, close to the source's database ordering. */
function compareText(a: string, b: string): number {
  return a.localeCompare(b, undefined, { sensitivity: "base" });
}

/** `ORDER BY Institution.name, Asset.product_name`. */
export function sortAssets<T extends Pick<AssetRow, "institution_name" | "product_name">>(
  rows: readonly T[],
): T[] {
  return [...rows].sort(
    (a, b) =>
      compareText(a.institution_name, b.institution_name) ||
      compareText(a.product_name, b.product_name),
  );
}

/**
 * The `WHERE` clause of `list_assets`.
 *
 * Search is a case-insensitive substring match over institution, product,
 * category and code/NIN (`ilike '%…%'`); the four selects are exact matches on
 * the *name*, not the id.
 */
export function filterAssets(
  rows: readonly AssetRow[],
  filters: Pick<AssetFilters, "search" | "currency" | "category" | "institution" | "tag">,
): AssetRow[] {
  const needle = filters.search.toLowerCase();

  return sortAssets(
    rows.filter((row) => {
      if (needle) {
        const haystack = [row.institution_name, row.product_name, row.category_name, row.code_nin ?? ""];
        if (!haystack.some((field) => field.toLowerCase().includes(needle))) return false;
      }
      if (filters.currency && row.currency !== filters.currency) return false;
      if (filters.category && row.category_name !== filters.category) return false;
      if (filters.institution && row.institution_name !== filters.institution) return false;
      if (filters.tag && !row.tags.some((tag) => tag.name === filters.tag)) return false;
      return true;
    }),
  );
}

export interface FilterChip {
  /** Query parameter the chip clears. */
  param: "search" | "currency" | "category" | "institution" | "tag";
  label: string;
}

/** The "Filters" chips under the form, in the template's order. */
export function activeFilterChips(filters: AssetFilters): FilterChip[] {
  const chips: FilterChip[] = [];
  if (filters.search) chips.push({ param: "search", label: `Search: "${filters.search}"` });
  if (filters.currency) chips.push({ param: "currency", label: `Currency: ${filters.currency}` });
  if (filters.category) chips.push({ param: "category", label: `Category: ${filters.category}` });
  if (filters.institution) chips.push({ param: "institution", label: `Institution: ${filters.institution}` });
  if (filters.tag) chips.push({ param: "tag", label: `Tag: ${filters.tag}` });
  return chips;
}

/** Distinct currencies across *all* assets, as the source's filter dropdown does. */
export function currencyOptions(rows: readonly Pick<AssetRow, "currency">[]): string[] {
  return [...new Set(rows.map((row) => row.currency).filter(Boolean))].sort();
}

// --- summary tiles ----------------------------------------------------------

export interface CurrencyBucket {
  currency: string;
  totalMinor: number;
  /** Assets that contributed a latest snapshot. */
  assets: number;
  /** Snapshots counted — one per asset here, as in the source. */
  snapshots: number;
}

export interface AssetListSummary {
  totalAssets: number;
  byCurrency: CurrencyBucket[];
  noSnapshotCount: number;
  /** Sum in the base currency, or null when a rate is missing (tile hidden). */
  combined: { totalMinor: number; currency: string } | null;
}

/**
 * The summary block of `list_assets`, computed over the *filtered* set so the
 * tiles always match the list.
 */
export function summariseAssetList(
  rows: readonly AssetRow[],
  rates: RateTable,
  baseCurrency: string,
): AssetListSummary {
  const buckets = new Map<string, CurrencyBucket>();
  let noSnapshotCount = 0;

  for (const row of rows) {
    const currency = row.currency || "Unknown";
    const bucket = buckets.get(currency) ?? { currency, totalMinor: 0, assets: 0, snapshots: 0 };
    buckets.set(currency, bucket);

    if (row.latest_amount_minor === null) {
      noSnapshotCount += 1;
      continue;
    }
    bucket.totalMinor += row.latest_amount_minor;
    bucket.assets += 1;
    bucket.snapshots += 1;
  }

  const byCurrency = [...buckets.values()];

  let combined: AssetListSummary["combined"] = null;
  if (byCurrency.length > 0) {
    try {
      let total = new Decimal(0);
      for (const bucket of byCurrency) {
        if (bucket.currency === "Unknown") throw new NoRateError("Unknown", baseCurrency);
        const major = fromMinorUnits(bucket.totalMinor) ?? new Decimal(0);
        total = total.plus(convertStrict(major, bucket.currency, baseCurrency, rates));
      }
      combined = {
        totalMinor: toMinorUnits(total),
        currency: baseCurrency,
      };
    } catch (error) {
      if (!(error instanceof NoRateError)) throw error;
      combined = null;
    }
  }

  return { totalAssets: rows.length, byCurrency, noSnapshotCount, combined };
}

// --- form -------------------------------------------------------------------

const decimalField = (label: string, max: number) =>
  z
    .string()
    .trim()
    .refine((value) => value === "" || !Number.isNaN(Number(value)), { message: `${label} must be a number` })
    .refine((value) => value === "" || (Number(value) >= 0 && Number(value) <= max), {
      message: `${label} must be between 0 and ${max}`,
    });

const requiredSelect = (message: string) => z.string().min(1, message);

/** Fields shared by the create and edit forms (`AssetForm`). */
export const assetFieldsSchema = z.object({
  institution_id: requiredSelect("Please select an institution."),
  category_id: requiredSelect("Please select a category."),
  product_name: z
    .string()
    .trim()
    .min(1, "Please enter a product name")
    .max(100, "Product name must be between 1 and 100 characters"),
  currency: z.enum(["EUR", "USD", "CHF"], { message: "Please select a currency" }),
  name: z.string().trim().max(100, "Custom name must be at most 100 characters"),
  description: z.string().trim().max(1000, "Description must be at most 1000 characters"),
  notes: z.string().trim().max(5000, "Notes must be at most 5000 characters"),
  code_nin: z.string().trim().max(50, "Code/NIN must be at most 50 characters"),
  cost_charges: decimalField("Cost/Charges", 100),
  interest_rate: decimalField("Interest Rate", 100),
  tags: z.array(z.string()),
});

export const assetEditSchema = assetFieldsSchema;

/** Create adds the optional first snapshot. */
export const assetCreateSchema = assetFieldsSchema
  .extend({
    create_initial_snapshot: z.boolean(),
    initial_amount: z.string().trim(),
    initial_date: z.string().trim(),
  })
  .superRefine((value, context) => {
    const amount = value.initial_amount;
    if (amount !== "" && (Number.isNaN(Number(amount)) || Number(amount) < 0.01)) {
      context.addIssue({
        code: "custom",
        path: ["initial_amount"],
        message: "Amount must be greater than 0",
      });
      return;
    }
    if (value.create_initial_snapshot && amount === "") {
      context.addIssue({
        code: "custom",
        path: ["initial_amount"],
        message: 'Please enter an initial amount or uncheck "Create Initial Snapshot".',
      });
    }
  });

export type AssetEditValues = z.infer<typeof assetEditSchema>;
export type AssetCreateValues = z.infer<typeof assetCreateSchema>;

/** Normalise an optional decimal the way WTForms' `DecimalField` hands it over. */
export function normaliseDecimal(value: string): string | null {
  const trimmed = value.trim();
  if (trimmed === "") return null;
  return new Decimal(trimmed).toString();
}

// --- detail page ------------------------------------------------------------

export interface HistoryRow {
  id: number;
  date: string;
  amount_minor: number;
  /** Change versus the previous (older) snapshot, in minor units; null for the oldest. */
  changeMinor: number | null;
  /** Fractional change (0.05 is +5%), null when there is no previous value or it is zero. */
  changeFraction: Decimal | null;
}

/**
 * Snapshot history, newest first, each row compared with the next-older one.
 *
 * Fixes a source bug: `detail.html` computes `(Δ / previous) * 100` and then
 * passes the result through the `percentage` filter, which multiplies by 100
 * again, so +5 % rendered as "+500.0%". Here the fraction goes to the filter.
 */
export function buildHistory(
  snapshots: ReadonlyArray<{ id: number; date: string; amount_minor: number }>,
): HistoryRow[] {
  const newestFirst = [...snapshots].sort((a, b) => b.date.localeCompare(a.date));

  return newestFirst.map((snapshot, index) => {
    const previous = newestFirst[index + 1];
    if (!previous) {
      return { ...snapshot, changeMinor: null, changeFraction: null };
    }
    const changeMinor = snapshot.amount_minor - previous.amount_minor;
    const changeFraction =
      previous.amount_minor === 0
        ? null
        : new Decimal(changeMinor).dividedBy(previous.amount_minor);
    return { ...snapshot, changeMinor, changeFraction };
  });
}
